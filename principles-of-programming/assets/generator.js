  // ───────────────────────── public API ─────────────────────────
  function byKey(k) { return FAMILIES.filter(function (f) { return f.key === k; })[0]; }
  function generate(key, seed) {
    var f = byKey(key);
    if (!f) return null;
    var p = f.make(tools(seed));
    p.id = 'gen~' + key + '~' + seed;
    p.topic = f.group + (f.group === 'Repetition' && key === 'pattern' ? ' (nested)' : '');
    p.level = f.level;
    p.generated = true;
    p.family = f.name;
    p.seed = seed;
    return p;
  }
  function parseId(id) {
    var m = /^gen~([a-z]+)~(\d+)$/.exec(id || '');
    return m ? generate(m[1], +m[2]) : null;
  }
  function randomSeed() { return Math.floor(Math.random() * 900000) + 100000; }
  function randomKey(group) {
    var pool = FAMILIES.filter(function (f) { return !group || group === 'Any' || f.group === group; });
    return pool[Math.floor(Math.random() * pool.length)].key;
  }

  window.Generator = { families: FAMILIES, generate: generate, parseId: parseId, randomSeed: randomSeed, randomKey: randomKey };
